def get_province(province_id: int) -> dict:
    """province_id로 단일 율령국 정보를 dict 형태로 반환"""
    hanja, hangul, region, modern, lon, lat, desc = PROVINCES[province_id]
    return {
        "id": province_id,
        "hanja": hanja,
        "hangul": hangul,
        "region": region,
        "region_name": REGIONS[region]["name"],
        "modern": modern,
        "lon": lon,
        "lat": lat,
        "desc": desc,
        "display": f"{province_id}. {hanja} ({hangul})",
    }


def all_provinces() -> list:
    """모든 율령국 정보를 id 오름차순 리스트로 반환"""
    return [get_province(pid) for pid in sorted(PROVINCES.keys())]


def search_provinces(query: str) -> list:
    """이름(한글/한자) 또는 번호로 율령국 검색"""
    if not query:
        return []
    query = query.strip()
    results = []
    for pid, (hanja, hangul, *_rest) in PROVINCES.items():
        if query == str(pid) or query in hangul or query in hanja:
            results.append(get_province(pid))
    return results
